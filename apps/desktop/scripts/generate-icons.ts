export const ICONS_FILE = join(import.meta.dirname, '../src/renderer/theme/icons.ts');

interface IconSet {
  width?: number;
  height?: number;
  icons: Record<string, { body: string; width?: number; height?: number }>;
}

/** The text of `icons.ts`, formatted as the repository's Prettier config wants it. */
export async function iconsModule(): Promise<string> {
  const require = createRequire(import.meta.url);
  const setFile = require.resolve('@iconify-json/tabler/icons.json');
  const set = JSON.parse(await readFile(setFile, 'utf8')) as IconSet;
  const { version } = JSON.parse(await readFile(join(setFile, '../package.json'), 'utf8')) as {
    version: string;
  };
  const entries = [...ICON_NAMES].sort().map((name) => {
    const icon = set.icons[name];
    if (!icon) throw new Error(`No icon "${name}" in @iconify-json/tabler ${version}.`);
    if ((icon.width ?? set.width) !== 24 || (icon.height ?? set.height) !== 24) {
      throw new Error(`Icon "${name}" is not drawn on the 24 × 24 grid.`);
    }
    return `  ${JSON.stringify(name)}: ${JSON.stringify(icon.body)},`;
  });
  const source = [
    `// Generated by scripts/generate-icons.ts from @iconify-json/tabler ${version}. Do not edit.`,
    '// Tabler Icons, MIT licence: see LICENCES.md.',
    '',
    '/** SVG bodies on a 24 × 24 grid, keyed by Tabler name. */',
    'export const ICONS = {',
    ...entries,
    '} as const;',
    '',
    'export type IconName = keyof typeof ICONS;',
    '',
  ].join('\n');
  const options = await resolveConfig(ICONS_FILE);
  return format(source, { ...options, filepath: ICONS_FILE });
}

if (import.meta.main) {
  await writeFile(ICONS_FILE, await iconsModule());
  console.log(`Wrote ${ICONS_FILE}`);
}
