/**
 * Writes `src/renderer/theme/icons.ts`: the SVG bodies of the Tabler icons the UI uses, copied
 * from `@iconify-json/tabler` at build time, so the renderer ships these few icons and not the
 * whole set. To use another icon, add its Tabler name to `ICON_NAMES` and run `npm run icons -w
 * @travelbook/desktop`. `generate-icons.test.ts` fails while the file is out of date.
 */
