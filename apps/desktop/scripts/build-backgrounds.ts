/**
 * Builds the bundled backgrounds: the pattern tiles (`resources/patterns/*.svg`), the paper
 * textures (`resources/textures/*.webp`) and `resources/backgrounds.json`, which lists every file
 * with its licence. All of it is our own work (CLEANROOM.md), released as CC0 by "travelbook".
 * The files are committed; `build-backgrounds.test.ts` fails while a file is missing from the
 * list, has no licence, or while a tile differs from what the generator produces.
 *
 *   npm run backgrounds -w @travelbook/desktop    write the files
 */
import { mkdir, readdir, rm, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { format, resolveConfig } from 'prettier';
import { patternTiles } from './backgrounds/patterns.ts';
import { TEXTURES, renderTexture } from './backgrounds/textures.ts';

export const RESOURCES_DIR = join(import.meta.dirname, '../resources');
export const PATTERNS_DIR = join(RESOURCES_DIR, 'patterns');
export const TEXTURES_DIR = join(RESOURCES_DIR, 'textures');
export const LIST_FILE = join(RESOURCES_DIR, 'backgrounds.json');

/** One line of `backgrounds.json`. `file` is relative to the resources folder. */
export interface BackgroundEntry {
  file: string;
  kind: 'pattern' | 'texture';
  title: string;
  source: string;
  author: string;
  licence: string;
  url: string;
}

const REPO_URL = 'https://github.com/corentinravoux/travelbook';
const SCRIPT_PATH = 'apps/desktop/scripts/build-backgrounds.ts';

export function entries(): BackgroundEntry[] {
  const common = {
    source: 'Generated by travelbook',
    author: 'travelbook',
    licence: 'CC0-1.0',
    url: `${REPO_URL}/blob/main/${SCRIPT_PATH}`,
  };
  return [
    ...patternTiles().map((t) => ({
      file: `patterns/${t.id}.svg`,
      kind: 'pattern' as const,
      title: t.title,
      ...common,
    })),
    ...TEXTURES.map((t) => ({
      file: `textures/${t.id}.webp`,
      kind: 'texture' as const,
      title: t.title,
      ...common,
    })),
  ];
}

async function emptyFolder(dir: string): Promise<void> {
  await mkdir(dir, { recursive: true });
  await Promise.all((await readdir(dir)).map((name) => rm(join(dir, name), { force: true })));
}

async function main(): Promise<void> {
  await emptyFolder(PATTERNS_DIR);
  await emptyFolder(TEXTURES_DIR);
  for (const tile of patternTiles())
    await writeFile(join(PATTERNS_DIR, `${tile.id}.svg`), tile.svg);
  for (const texture of TEXTURES) {
    await writeFile(join(TEXTURES_DIR, `${texture.id}.webp`), await renderTexture(texture));
  }
  const options = (await resolveConfig(LIST_FILE)) ?? {};
  await writeFile(
    LIST_FILE,
    await format(JSON.stringify(entries()), { ...options, parser: 'json' }),
  );
}

if (process.argv[1] === import.meta.filename) await main();
